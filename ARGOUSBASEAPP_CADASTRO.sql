);

CREATE TABLE Cadastro.SETOR
(
	ID_SETOR Integer NOT NULL,
	ID_USUARIO_INCLUSAO UUID NOT NULL,
	ID_USUARIO_ALTERACAO UUID NULL ,
	ID_UNIDADE Smallint NOT NULL,
	NM_SETOR Varchar(100) NOT NULL,
