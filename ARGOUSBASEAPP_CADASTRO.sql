(
	ID_PROGRAMA UUID NOT NULL,
	ID_PROGRAMA_PAI UUID NULL ,
	CD_PROGRAMA Varchar(70) NOT NULL Constraint uk_programas_codigo UNIQUE ,
	DS_NOME Varchar(120) NOT NULL,
