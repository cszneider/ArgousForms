	DT_INCLUSAO Timestamp NOT NULL Default CURRENT_TIMESTAMP,
	DT_ALTERACAO Timestamp NOT NULL Default CURRENT_TIMESTAMP,
	DT_EXCLUSAO Timestamp NULL ,
