	CONSTRAINT ck_encaminhamento_teste CHECK ((TP_ENCAMINHAMENTO = 'E' AND TX_TESTE IS NULL)
	  OR (TP_ENCAMINHAMENTO IN ('T', 'C') AND BTRIM(COALESCE(TX_TESTE, '')) <> ''))
