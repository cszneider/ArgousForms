-- A data registra mudanças de metadados, independentemente da inclusão de novas versões.
CREATE OR REPLACE FUNCTION Docs.definir_alteracao_metadados_arquivo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.DT_ALTERACAO := NEW.DT_INCLUSAO;
    ELSIF (NEW.DS_TITULO, NEW.DS_DESCRICAO, NEW.TP_CLASSIFICACAO) IS DISTINCT FROM (OLD.DS_TITULO, OLD.DS_DESCRICAO, OLD.TP_CLASSIFICACAO) THEN
        NEW.DT_ALTERACAO := GREATEST(CURRENT_TIMESTAMP, NEW.DT_INCLUSAO);
    ELSE
        NEW.DT_ALTERACAO := OLD.DT_ALTERACAO;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_definir_alteracao_metadados_arquivo BEFORE INSERT OR UPDATE ON Docs.ARQUIVOS FOR EACH ROW EXECUTE FUNCTION Docs.definir_alteracao_metadados_arquivo();


CREATE SCHEMA IF NOT EXISTS Notificacoes;

CREATE TABLE Notificacoes.EVENTOS
(
    ID_EVENTO UUID NOT NULL,
    CD_TIPO Varchar(40) NOT NULL Check (BTRIM(CD_TIPO) <> ''),
    ID_PROCESSO UUID NULL,
    ID_PROCESSO_ETAPA UUID NULL,
    ID_PROTOCOLO_VERSAO UUID NULL,
    ID_USUARIO_ATOR UUID NULL,
    DT_EVENTO Timestamp with time zone NOT NULL,
    DS_TITULO Varchar(160) NOT NULL Check (BTRIM(DS_TITULO) <> ''),
    DS_RESUMO Text NULL,
    CD_CHAVE_EVENTO Varchar(160) NOT NULL UNIQUE Check (BTRIM(CD_CHAVE_EVENTO) <> ''),
    CONSTRAINT ck_notificacao_evento_etapa_processo CHECK (ID_PROCESSO_ETAPA IS NULL OR ID_PROCESSO IS NOT NULL),
    PRIMARY KEY (ID_EVENTO)
);

CREATE TABLE Notificacoes.NOTIFICACOES
(
    ID_NOTIFICACAO UUID NOT NULL,
    ID_EVENTO UUID NOT NULL,
    ID_USUARIO_DESTINO UUID NOT NULL,
    TP_NATUREZA Char(1) NOT NULL Check (TP_NATUREZA IN ('A', 'I')),
    DT_ENTREGA Timestamp with time zone NOT NULL,
    DT_VISUALIZACAO Timestamp with time zone NULL Check (DT_VISUALIZACAO IS NULL OR DT_VISUALIZACAO >= DT_ENTREGA),
    TP_SITUACAO Char(1) NOT NULL Check (TP_SITUACAO IN ('P', 'A', 'E', 'C', 'I')),
    DT_ENCERRAMENTO Timestamp with time zone NULL Check (DT_ENCERRAMENTO IS NULL OR DT_ENCERRAMENTO >= DT_ENTREGA),
    ID_USUARIO_ATENDEU UUID NULL,
    DS_RESULTADO Text NULL Check (DS_RESULTADO IS NULL OR BTRIM(DS_RESULTADO) <> ''),
    CONSTRAINT ck_notificacao_natureza_situacao CHECK ((TP_NATUREZA = 'I' AND TP_SITUACAO = 'I') OR (TP_NATUREZA = 'A' AND TP_SITUACAO IN ('P', 'A', 'E', 'C'))),
    CONSTRAINT ck_notificacao_encerramento CHECK ((TP_SITUACAO IN ('P', 'I') AND DT_ENCERRAMENTO IS NULL) OR (TP_SITUACAO IN ('A', 'E', 'C') AND DT_ENCERRAMENTO IS NOT NULL)),
    PRIMARY KEY (ID_NOTIFICACAO)
);

CREATE UNIQUE INDEX uq_notificacao_pendente_usuario_evento ON Notificacoes.NOTIFICACOES (ID_EVENTO, ID_USUARIO_DESTINO) WHERE TP_SITUACAO = 'P';
