CREATE INDEX ix_notificacao_nao_lida ON Notificacoes.NOTIFICACOES (ID_USUARIO_DESTINO, DT_ENTREGA DESC) WHERE DT_VISUALIZACAO IS NULL AND TP_SITUACAO IN ('P', 'I');
